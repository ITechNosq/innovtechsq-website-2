// Innovtechnosq - Premium Frontend Logic
document.addEventListener('DOMContentLoaded', function() {
    // Initialize AOS
    if (typeof AOS !== 'undefined') {
        AOS.init({ duration: 1000, once: true });
    }
    
    initNavigation();
    initForm();
    initWhatsApp();
});

// 1. WhatsApp Redirection Logic
function initWhatsApp() {
    document.querySelectorAll('[data-whatsapp]').forEach(btn => {
        btn.addEventListener('click', function(e) {
            e.preventDefault();
            const number = window.CONFIG?.WHATSAPP_NUMBER || '918595237962';
            const msg = window.CONFIG?.WHATSAPP_MESSAGE || 'Hi, I want to submit a Service Request.';
            window.open(`https://wa.me/${number}?text=${encodeURIComponent(msg)}`, '_blank');
        });
    });
}

// 2. Service Request (SR) Form Submission
function initForm() {
    const form = document.querySelector('[data-contact-form]');
    const messageDiv = document.getElementById('form-message');
    
    if (!form || !messageDiv) return;
    
    form.addEventListener('submit', function(e) {
        e.preventDefault();
        
        const data = {
            name: form.querySelector('[data-name]').value.trim(),
            email: form.querySelector('[data-email]').value.trim(),
            phone: form.querySelector('[data-phone]').value.trim(),
            service_type: form.querySelector('[data-service-type]')?.value || 'General IT',
            message: form.querySelector('[data-message]').value.trim(),
            // Turnstile token generated by Cloudflare widget (cf-turnstile-response)
            turnstile_token: form.querySelector('[name="turnstile_token"]')?.value || ""

        };
        
        showMessage('Processing Service Request...', 'info');
        
        const apiUrl = window.CONFIG?.API_URL || 'http://localhost:8000';
        
        fetch(`${apiUrl}/leads`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(data)
        })
        .then(async (response) => {
            if (!response.ok) {
                let errBody = null;
                try { errBody = await response.json(); } catch (_) {}
                const detail = errBody?.detail || errBody?.error_code || `Request failed (${response.status})`;
                throw new Error(detail);
            }
            return response.json();
        })

        .then((res) => {
            const srId = `SR-${res.lead_id.toString().padStart(4, '0')}`;
            showMessage(`✅ Service Request submitted! Your ID is ${srId}. Check your email for confirmation.`, 'success');
            form.reset();
        })
        .catch((error) => {
            console.error('SR Error:', error);
            showMessage(`❌ Error: ${error.message}`, 'error');
        });
    });
}

function showMessage(text, type) {
    const msg = document.getElementById('form-message');
    if (!msg) return;
    
    msg.textContent = text;
    msg.className = `p-4 rounded-xl text-sm font-medium mb-6 ${
        type === 'success' ? 'bg-emerald-500/10 border border-emerald-500/20 text-emerald-400' : 
        type === 'error' ? 'bg-red-500/10 border border-red-500/20 text-red-400' : 
        'bg-blue-500/10 border border-blue-500/20 text-blue-400'
    }`;
    msg.classList.remove('hidden');
}

// 3. Smooth Scrolling
function initNavigation() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                window.scrollTo({
                    top: target.offsetTop - 80,
                    behavior: 'smooth'
                });
            }
        });
    });
}
